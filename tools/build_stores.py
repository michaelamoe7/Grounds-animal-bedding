"""Merge per-retailer store lists into js/stores.js for the store map.

Usage: python3 tools/build_stores.py [data/stores]
Each input file is a JSON array of {name, street, city, state, zip, lat, lon, url}.
Stores without coordinates are placed at their ZIP code centre (pip install zipcodes).
"""
import json, sys, os, re

FILES = {  # input file name -> retailer name shown on the map
    "atp_rural_king_us.json": "Rural King",
    "atwoods.json": "Atwoods",
    "atp_bomgaars_us.json": "Bomgaars",
    "murdochs.json": "Murdoch's",
    "atp_fleet_farm_us.json": "Fleet Farm",
    "atp_runnings_us.json": "Runnings",
    "familyfarmandhome.json": "Family Farm & Home",
    "farmandhomesupply.json": "Farm & Home Supply",
    "theisens.json": "Theisen's",
    "buchheit.json": "Buchheit",
    "atp_big_r_farm_and_home_us.json": "Big R Farm & Home",
    "atp_big_r_stores_us.json": "Big R Stores",
}

def zip_centre(z):
    try:
        import zipcodes
        m = zipcodes.matching(z)
        if m: return float(m[0]["lat"]), float(m[0]["long"])
    except Exception:
        pass
    return None

def main(src):
    out, report = [], []
    for fn, retailer in FILES.items():
        path = os.path.join(src, fn)
        if not os.path.exists(path):
            report.append(f"{retailer}: MISSING"); continue
        rows = json.load(open(path)); n = approx = dropped = 0
        seen = set()
        for r in rows:
            lat, lon = r.get("lat"), r.get("lon")
            if lat in (None, "") or lon in (None, ""):
                c = zip_centre((r.get("zip") or "")[:5])
                if not c: dropped += 1; continue
                lat, lon = c; approx += 1
            lat, lon = round(float(lat), 5), round(float(lon), 5)
            if not (18 < lat < 72 and -170 < lon < -60): dropped += 1; continue
            key = (round(lat, 3), round(lon, 3))
            if key in seen: continue
            seen.add(key)
            city = (r.get("city") or "").strip().title() if (r.get("city") or "").isupper() else (r.get("city") or "").strip()
            out.append({"r": retailer, "s": (r.get("street") or "").strip(), "c": city,
                        "st": (r.get("state") or "").strip().upper(), "z": (r.get("zip") or "")[:5],
                        "lat": lat, "lon": lon, "u": r.get("url") or ""})
            n += 1
        report.append(f"{retailer}: {n} stores ({approx} placed by ZIP, {dropped} dropped)")
    out.sort(key=lambda x: (x["r"], x["st"], x["c"]))
    os.makedirs("js", exist_ok=True)
    with open("js/stores.js", "w") as f:
        f.write("// Generated by tools/build_stores.py. Store locations for the map.\n")
        f.write("window.GROUNDS_STORES = " + json.dumps(out, separators=(",", ":"), ensure_ascii=False) + ";\n")
    print("\n".join(report)); print("TOTAL", len(out))

if __name__ == "__main__":
    main(sys.argv[1] if len(sys.argv) > 1 else "data/stores")
